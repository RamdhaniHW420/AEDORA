const DICT: Record<Lang, Record<Key, string>> = { id, en };

function fmt(s: string, p?: Record<string, string | number>): string {
  return p ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(p[k] ?? '')) : s;
}

/** Terjemahan di luar komponen (mis. pesan galat). */
export function tr(key: Key, p?: Record<string, string | number>): string {
  return fmt(DICT[useLang.getState().lang][key], p);
}

/** Hook: komponen otomatis dirender ulang saat bahasa berganti. */
export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: Key, p?: Record<string, string | number>) => fmt(DICT[lang][key], p);
}
