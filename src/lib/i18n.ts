import { useEffect } from 'react';
import { create } from 'zustand';
import { getJSON, setJSON } from '@/lib/storage';

export type Lang = 'id' | 'en';
const KEY = 'aedora:lang';

interface LangState {
  lang: Lang;
  loaded: boolean;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>((set) => ({
  lang: 'id',
  loaded: false,
  setLang: (l) => {
    set({ lang: l });
    void setJSON(KEY, l);
  },
}));

/** Muat bahasa tersimpan. Panggil sekali di layout root. */
export function useInitLang() {
  useEffect(() => {
    void getJSON<Lang>(KEY, 'id').then((l) => useLang.setState({ lang: l === 'en' ? 'en' : 'id', loaded: true }));
  }, []);
}

